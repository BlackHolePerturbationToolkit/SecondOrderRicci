using namespace std;
using boost::multi_array;
typedef boost::multi_array_types::extent_range range;

const double M = 1.0;

typedef void (*R2G_function)(const double, const double, const vector<double>&, const vector<double>&,
                             const vector<double>&, const ModeBlock&, const ModeBlock&, const ModeBlock&,
                             const ModeBlock&, const ModeBlock&, const ModeBlock&,
                             int, int, int, int, complex<double> *const*, size_t, size_t);
typedef void (*R2C_function)(int, int, int, int, int, int, double*);
static const R2G_function R2G[11] = {nullptr, R2G_1, R2G_2, R2G_3, R2G_4, R2G_5, R2G_6, R2G_7, R2G_8, R2G_9, R2G_10};
static const R2C_function R2C[11] = {nullptr, R2C_1, R2C_2, R2C_3, R2C_4, R2C_5, R2C_6, R2C_7, R2C_8, R2C_9, R2C_10};

struct Interval { size_t jb, je; };
struct LPair { int l1, l2; };

/* (l1, l2) pairs of shell s = max(l1, l2) that couple to l3, within
 * l3-dlmax <= l1, l2 <= l3+dlmax and l1, l2 <= h1lmax. */
static vector<LPair> shell_pairs(int l3, int s, int dlmax, int h1lmax)
{
  vector<LPair> p;
  if (s > h1lmax || s < l3 - dlmax || s > l3 + dlmax) return p;
  auto ok = [&](int l1, int l2) {
    return l1 >= 0 && l2 >= 0 && l1 >= l3 - dlmax && l2 >= l3 - dlmax && l1 <= l3 + dlmax && l2 <= l3 + dlmax
           && abs(l1 - l2) <= l3 && l3 <= l1 + l2;
  };
  for (int l2 = 0; l2 <= s; ++l2)       /* l1 = s */
    if (ok(s, l2)) p.push_back({s, l2});
  for (int l1 = 0; l1 < s; ++l1)        /* l2 = s, l1 < s */
    if (ok(l1, s)) p.push_back({l1, s});
  return p;
}

int main(int argc, char* argv[])
{
  cout << "Version: " << __GIT_VERSION << endl;

  vector<string> pos;
  double skip_lo = 0, skip_hi = 0;
  bool skip = false;
  bool shells = false;          /* sum in shells s = max(l1, l2) instead of the original order */
  int diag_l3max = -1;          /* record per-shell sums for output modes with l3 <= diag_l3max */
  bool l3reuse = false;          /* compute each (l1, m1, l2, m2) term once for all output l3 */
  int nchunks = 0;               /* radial chunks per (i3, m3) task with --l3-reuse (0: automatic) */
  bool adaptive = false;        /* per-point truncation of the shell sum (with Wynn acceleration) */
  double adapt_tol = 1e-10, adapt_floor = 1e-6;
  int adapt_window = 21, adapt_confirm = 3, adapt_min_shells = 6;
  bool adapt_accel = true;
  for (int a = 1; a < argc; ++a) {
    string s = argv[a];
    if (s == "--skip-interior" && a + 2 < argc) {
      skip = true;
      skip_lo = atof(argv[++a]);
      skip_hi = atof(argv[++a]);
    } else if (s == "--l3-reuse") {
      l3reuse = true;
    } else if (s == "--chunks" && a + 1 < argc) {
      nchunks = atoi(argv[++a]);
    } else if (s == "--shells") {
      shells = true;
    } else if (s == "--adaptive" && a + 1 < argc) {
      shells = true; adaptive = true;
      adapt_tol = atof(argv[++a]);
    } else if (s == "--window" && a + 1 < argc) {
      adapt_window = atoi(argv[++a]);
    } else if (s == "--floor" && a + 1 < argc) {
      adapt_floor = atof(argv[++a]);
    } else if (s == "--min-shells" && a + 1 < argc) {
      adapt_min_shells = atoi(argv[++a]);
    } else if (s == "--confirm" && a + 1 < argc) {
      adapt_confirm = atoi(argv[++a]);
    } else if (s == "--no-accel") {
      adapt_accel = false;
    } else if (s == "--shell-diagnostics" && a + 1 < argc) {
      shells = true;
      diag_l3max = atoi(argv[++a]);
    } else {
      pos.push_back(s);
    }
  }
  string dirA, dirB;
  if (pos.size() == 1) {
    dirA = dirB = pos[0];
  } else if (pos.size() == 4) {
    dirA = pos[0];
    dirB = pos[1];
  } else {
    cout << "Usage: " << argv[0] << " <dirA> [<dirB> <delta lmax> <lmax>] [--skip-interior <rlo> <rhi>]" << endl;
    exit(1);
  }

  int num_threads = 1;
#ifdef _OPENMP
  num_threads = omp_get_max_threads();
  cout << "Running with " << num_threads << " OpenMP threads" << endl;
#endif

  /* Read in first-order fields (packed; one copy when both inputs are the same) */
  vector<double> r, f, fp;
  double r0;
  int r0i;
  Field hA_store, dhA_store, ddhA_store, hB_store, dhB_store, ddhB_store;
  const int lmaxA = read_h1(dirA, r0, r0i, r, f, fp, hA_store, dhA_store, ddhA_store, numeric_limits<int>::max());
  int lmaxB = lmaxA;
  const bool same = (dirA == dirB);
  if (!same)
    lmaxB = read_h1(dirB, r0, r0i, r, f, fp, hB_store, dhB_store, ddhB_store, numeric_limits<int>::max());
  else
    cout << "Both inputs are " << dirA << ": sharing one copy" << endl;
  const Field &hA = hA_store, &dhA = dhA_store, &ddhA = ddhA_store;
  const Field &hB = same ? hA_store : hB_store, &dhB = same ? dhA_store : dhB_store,
              &ddhB = same ? ddhA_store : ddhB_store;
  int h1lmax = min(lmaxA, lmaxB);
  const size_t N = r.size();

  int lmax, dlmax;
  if (pos.size() == 1) {
    dlmax = lmax = h1lmax;
  } else {
    dlmax = atoi(pos[2].c_str());
    if (dlmax < 0) {
      h1lmax += dlmax;
      dlmax = h1lmax;
    } else {
      dlmax = min(dlmax, h1lmax);
    }
    lmax = min(atoi(pos[3].c_str()), h1lmax);
  }

  /* Radial ranges to compute */
  vector<Interval> ranges;
  if (skip) {
    size_t j = 0;
    while (j < N && r[j] <= skip_lo) ++j;
    if (j > 0) ranges.push_back({0, j});
    size_t k = j;
    while (k < N && r[k] < skip_hi) ++k;
    if (k < N) ranges.push_back({k, N});
    cout << "Skipping " << (k - j) << " grid points with " << skip_lo << " < r < " << skip_hi << endl;
  } else {
    ranges.push_back({0, N});
  }

  /* Compute the source */
  multi_array<complex<double>,4> src(boost::extents[range(1,11)][lmax+1][lmax+1][N]);
  fill(src.data(), src.data() + src.num_elements(), 0.0);

  vector<ilm_mode> modes;
  for (int l3 = 0; l3 <= lmax; ++l3)
    for (int m3 = 0; m3 <= l3; ++m3)
      for (int i3 = 1; i3 <= 10; ++i3) {
        if (((i3 <= 7) && isOdd(l3+m3)) || ((i3 > 7) && isEven(l3+m3))) continue;
        if (((i3 == 4) || (i3 == 5) || (i3 == 8) || (i3 == 9)) && l3 < 1) continue;
        if (((i3 == 7) || (i3 == 10)) && l3 < 2) continue;
        modes.push_back(ilm_mode({i3, l3, m3}));
      }

  cout << "Computing source: " << modes.size() << " (i,l,m) modes, l_max = " << lmax
       << ", delta l_max = " << dlmax << endl;

  struct DiagEntry { ilm_mode mode; multi_array<double,3> *data; };
  vector<DiagEntry> diag_store;
  struct ConvEntry { ilm_mode mode; vector<int> shells; vector<char> unconverged; };
  vector<ConvEntry> conv_store;
  if (adaptive) cout << "Adaptive per-point truncation: tol = " << adapt_tol << ", floor = " << adapt_floor
                     << ", window = " << adapt_window << ", confirm = " << adapt_confirm << ", min shells = " << adapt_min_shells
                     << (adapt_accel ? ", Wynn epsilon acceleration" : ", no acceleration") << endl;
  if (shells) cout << "Summing in shells s = max(l1, l2)" << endl;

  int status = 0;
  const int status_frequency = 4*num_threads;
  const int num_modes = modes.size();
  if (l3reuse) {
    /* ---------------------------------------------------------------------------------
     * l3 reuse: d2R_i(l3, m3) = sum_k c_k(l3, m3, l1, m1, l2, m2) G_ik(l1, m1, l2, m2), with
     * G_ik independent of l3. Tasks are (i3, m3, radial chunk); each computes G_ik once per
     * (l1, m1, l2, m2 = m3 - m1) and adds it to every output l3 it couples to. Each output
     * value is computed by exactly one task, in a fixed order (independent of threads).
     * ------------------------------------------------------------------------------- */
    struct Task { int i3, m3; size_t jb, je; vector<int> l3s; };
    auto l3_allowed = [&](int i3, int l3, int m3) {
      if (((i3 <= 7) && isOdd(l3+m3)) || ((i3 > 7) && isEven(l3+m3))) return false;
      if (((i3 == 4) || (i3 == 5) || (i3 == 8) || (i3 == 9)) && l3 < 1) return false;
      if (((i3 == 7) || (i3 == 10)) && l3 < 2) return false;
      return true;
    };
    vector<Task> tasks;
    size_t npts = 0;
    for (const Interval &iv : ranges) npts += iv.je - iv.jb;
    int nim = 0;
    for (int i3 = 1; i3 <= 10; ++i3)
      for (int m3 = 0; m3 <= lmax; ++m3) {
        bool any = false;
        for (int l3 = m3; l3 <= lmax; ++l3) any = any || l3_allowed(i3, l3, m3);
        nim += any;
      }
    int nch = nchunks > 0 ? nchunks : max(1, (4*num_threads + nim - 1)/max(nim, 1));
    const size_t chunk = max<size_t>(1, (npts + nch - 1)/nch);
    for (int i3 = 1; i3 <= 10; ++i3)
      for (int m3 = 0; m3 <= lmax; ++m3) {
        vector<int> l3s;
        for (int l3 = m3; l3 <= lmax; ++l3) if (l3_allowed(i3, l3, m3)) l3s.push_back(l3);
        if (l3s.empty()) continue;
        for (const Interval &iv : ranges)
          for (size_t jb = iv.jb; jb < iv.je; jb += chunk)
            tasks.push_back({i3, m3, jb, min(iv.je, jb + chunk), l3s});
      }
    /* biggest tasks first: low m3 couples to the most l3 */
    stable_sort(tasks.begin(), tasks.end(), [](const Task &a, const Task &b) { return a.l3s.size() > b.l3s.size(); });
    cout << "l3 reuse: " << tasks.size() << " tasks ((i3, m3) x " << nch << " radial chunks of <= " << chunk << " points)" << endl;

    /* convergence diagnostics per output mode, assembled from the chunks */
    vector<vector<int>> conv_shells(modes.size());
    vector<vector<char>> conv_unconv(modes.size());
    auto mode_index = [&](int i3, int l3, int m3) {
      for (size_t k = 0; k < modes.size(); ++k)
        if (modes[k].i == i3 && modes[k].l == l3 && modes[k].m == m3) return (int)k;
      return -1;
    };
    if (adaptive)
      for (size_t k = 0; k < modes.size(); ++k) { conv_shells[k].assign(N, 0); conv_unconv[k].assign(N, 0); }

    int done = 0;
#pragma omp parallel
    {
      ModeBuffer bh1, bdh1, bddh1, bh2, bdh2, bddh2;
      bh1.reserve(N); bdh1.reserve(N); bddh1.reserve(N);
      bh2.reserve(N); bdh2.reserve(N); bddh2.reserve(N);
      ModeBlock Bh1, Bdh1, Bddh1, Bh2, Bdh2, Bddh2;
      vector<complex<double>> Gbuf(static_cast<size_t>(R2_NC_MAX)*N);
      complex<double> *G[R2_NC_MAX];
      for (int k = 0; k < R2_NC_MAX; ++k) G[k] = Gbuf.data() + static_cast<size_t>(k)*N;
      double c[R2_NC_MAX];

#pragma omp for schedule(dynamic)
      for (size_t it = 0; it < tasks.size(); ++it) {
        const Task &t = tasks[it];
        const int i3 = t.i3, m3 = t.m3, K = R2_NC[i3];
        const size_t jb = t.jb, je = t.je, len = je - jb;
        const size_t nl = t.l3s.size();
        vector<complex<double>*> out(nl);
        for (size_t a = 0; a < nl; ++a) out[a] = &src[i3][t.l3s[a]][m3][0];

        auto group_valid = [&](int l1, int l2, int l3) {
          return abs(l1 - l2) <= l3 && l3 <= l1 + l2 && l1 >= l3 - dlmax && l2 >= l3 - dlmax
                 && l1 <= l3 + dlmax && l2 <= l3 + dlmax;
        };
        /* compute G for (l1, m1, l2) on the given intervals and add sum_k c_k G_k to the
         * outputs l3 in `targets` */
        auto do_group = [&](int l1, int m1, int l2, const vector<Interval> &ivs, const vector<size_t> &targets) {
          const int m2 = m3 - m1;
          for (const Interval &iv : ivs) {
            bh1.resolve(hA, l1, m1, iv.jb, iv.je, Bh1);
            bdh1.resolve(dhA, l1, m1, iv.jb, iv.je, Bdh1);
            bddh1.resolve(ddhA, l1, m1, iv.jb, iv.je, Bddh1);
            bh2.resolve(hB, l2, m2, iv.jb, iv.je, Bh2);
            bdh2.resolve(dhB, l2, m2, iv.jb, iv.je, Bdh2);
            bddh2.resolve(ddhB, l2, m2, iv.jb, iv.je, Bddh2);
            for (int k = 0; k < K; ++k) fill(G[k] + iv.jb, G[k] + iv.je, complex<double>(0.0, 0.0));
            R2G[i3](M, r0, r, f, fp, Bh1, Bdh1, Bddh1, Bh2, Bdh2, Bddh2, l1, m1, l2, m2, G, iv.jb, iv.je);
          }
          for (size_t a : targets) {
            R2C[i3](t.l3s[a], m3, l1, m1, l2, m2, c);
            complex<double> *o = out[a];
            for (const Interval &iv : ivs)
              for (size_t j = iv.jb; j < iv.je; ++j) {
                complex<double> v = 0.0;
                for (int k = 0; k < K; ++k) v += c[k]*G[k][j];
                o[j] += v;
              }
          }
        };

        vector<size_t> targets;
        if (!adaptive) {
          const vector<Interval> ivs{{jb, je}};
          for (int l1 = 0; l1 <= h1lmax; ++l1)
            for (int l2 = 0; l2 <= h1lmax; ++l2) {
              targets.clear();
              for (size_t a = 0; a < nl; ++a) if (group_valid(l1, l2, t.l3s[a])) targets.push_back(a);
              if (targets.empty()) continue;
              for (int m1 = -l1; m1 <= l1; ++m1)
                if (abs(m3 - m1) <= l2) do_group(l1, m1, l2, ivs, targets);
            }
        } else {
          /* adaptive: shells s = max(l1, l2); per-point convergence for each output l3 */
          vector<ShellConvergence> conv;
          conv.reserve(nl);
          vector<vector<complex<double>>> part(nl, vector<complex<double>>(len));
          for (size_t a = 0; a < nl; ++a)
            conv.emplace_back(len, adapt_window, adapt_tol, adapt_floor, adapt_confirm, adapt_accel, adapt_min_shells);
          vector<char> shell_has(nl);
          vector<Interval> act;
          for (int sh = 0; sh <= h1lmax; ++sh) {
            /* points still active for any output l3 */
            act.clear();
            for (size_t j = 0; j < len; ) {
              bool any = false;
              for (size_t a = 0; a < nl && !any; ++a) any = conv[a].active(j);
              if (!any) { ++j; continue; }
              size_t k = j + 1;
              while (k < len) {
                bool anyk = false;
                for (size_t a = 0; a < nl && !anyk; ++a) anyk = conv[a].active(k);
                if (!anyk) break;
                ++k;
              }
              act.push_back({jb + j, jb + k});
              j = k;
            }
            if (act.empty()) break;
            fill(shell_has.begin(), shell_has.end(), 0);
            for (int l1 = 0; l1 <= sh; ++l1)
              for (int l2 = 0; l2 <= sh; ++l2) {
                if (max(l1, l2) != sh) continue;
                targets.clear();
                for (size_t a = 0; a < nl; ++a)
                  if (conv[a].num_active() > 0 && group_valid(l1, l2, t.l3s[a])) targets.push_back(a);
                if (targets.empty()) continue;
                for (size_t a : targets) shell_has[a] = 1;
                for (int m1 = -l1; m1 <= l1; ++m1)
                  if (abs(m3 - m1) <= l2) do_group(l1, m1, l2, act, targets);
              }
            for (size_t a = 0; a < nl; ++a)
              if (shell_has[a]) conv[a].update(out[a] + jb);
          }
          for (size_t a = 0; a < nl; ++a) {
            const vector<complex<double>> &est = conv[a].estimates();
            for (size_t j = 0; j < len; ++j) out[a][jb + j] = est[j];
            const int mi = mode_index(i3, t.l3s[a], m3);
            const vector<int> &sh = conv[a].shells_used();
            const vector<char> uc = conv[a].unconverged();
            for (size_t j = 0; j < len; ++j) { conv_shells[mi][jb + j] = sh[j]; conv_unconv[mi][jb + j] = uc[j]; }
          }
        }
#pragma omp critical
        {
          if (++done % max(1, (int)tasks.size()/20) == 0)
            cout << "Finished " << done << " of " << tasks.size() << " tasks" << endl;
        }
      }
    }
    if (adaptive)
      for (size_t k = 0; k < modes.size(); ++k)
        conv_store.push_back({modes[k], conv_shells[k], conv_unconv[k]});
    status = num_modes;
  } else {
#pragma omp parallel
  {
    /* per-thread scratch */
    ModeBuffer bh1, bdh1, bddh1, bh2, bdh2, bddh2;
    bh1.reserve(N); bdh1.reserve(N); bddh1.reserve(N);
    bh2.reserve(N); bdh2.reserve(N); bddh2.reserve(N);
    ModeBlock Bh1, Bdh1, Bddh1, Bh2, Bdh2, Bddh2;
    vector<complex<double>> Gbuf(static_cast<size_t>(R2_NC_MAX)*N);
    complex<double> *G[R2_NC_MAX];
    for (int k = 0; k < R2_NC_MAX; ++k) G[k] = Gbuf.data() + static_cast<size_t>(k)*N;
    double c[R2_NC_MAX];

#pragma omp for schedule(dynamic)
    for (int im = 0; im < num_modes; ++im) {
      const int i3 = modes[im].i, l3 = modes[im].l, m3 = modes[im].m;
      complex<double> *out = &src[i3][l3][m3][0];
      const int K = R2_NC[i3];

      /* One coupling term (l1, m1, l2, m2 = m3 - m1) added into acc on the active ranges */
      auto add_term_on = [&](const vector<Interval> &ivs, int l1, int m1, int l2, complex<double> *acc) {
        const int m2 = m3 - m1;
        for (const Interval &iv : ivs) {
          bh1.resolve(hA, l1, m1, iv.jb, iv.je, Bh1);
          bdh1.resolve(dhA, l1, m1, iv.jb, iv.je, Bdh1);
          bddh1.resolve(ddhA, l1, m1, iv.jb, iv.je, Bddh1);
          bh2.resolve(hB, l2, m2, iv.jb, iv.je, Bh2);
          bdh2.resolve(dhB, l2, m2, iv.jb, iv.je, Bdh2);
          bddh2.resolve(ddhB, l2, m2, iv.jb, iv.je, Bddh2);
          for (int k = 0; k < K; ++k) fill(G[k] + iv.jb, G[k] + iv.je, complex<double>(0.0, 0.0));
          R2G[i3](M, r0, r, f, fp, Bh1, Bdh1, Bddh1, Bh2, Bdh2, Bddh2, l1, m1, l2, m2, G, iv.jb, iv.je);
        }
        R2C[i3](l3, m3, l1, m1, l2, m2, c);
        for (const Interval &iv : ivs)
          for (size_t j = iv.jb; j < iv.je; ++j) {
            complex<double> v = 0.0;
            for (int k = 0; k < K; ++k) v += c[k]*G[k][j];
            acc[j] += v;
          }
      };
      auto add_term = [&](int l1, int m1, int l2, complex<double> *acc) { add_term_on(ranges, l1, m1, l2, acc); };

      if (!shells) {
        /* Original order: l1, then l2, then m1 (bit-compatible accumulation) */
        for (int l1 = max(0, l3-dlmax); l1 <= min(h1lmax, l3+dlmax); ++l1)
          for (int l2 = max(abs(l3-l1), l3-dlmax); l2 <= min(min(l3+l1, h1lmax), l3+dlmax); ++l2)
            for (int m1 = -l1; m1 <= l1; ++m1)
              if (abs(m3 - m1) <= l2)
                add_term(l1, m1, l2, out);
      } else if (adaptive) {
        /* Shells with per-point convergence: only points that have not converged are
         * computed; converged points keep their (Wynn-accelerated) estimate. */
        ShellConvergence conv(N, adapt_window, adapt_tol, adapt_floor, adapt_confirm, adapt_accel, adapt_min_shells);
        {
          size_t prev = 0;
          for (const Interval &iv : ranges) { conv.deactivate(prev, iv.jb); prev = iv.je; }
          conv.deactivate(prev, N);
        }
        vector<Interval> act;
        for (int sh = 0; sh <= h1lmax && conv.num_active() > 0; ++sh) {
          vector<LPair> pairs = shell_pairs(l3, sh, dlmax, h1lmax);
          if (pairs.empty()) continue;
          act.clear();
          for (size_t j = 0; j < N; ) {
            if (!conv.active(j)) { ++j; continue; }
            size_t k = j;
            while (k < N && conv.active(k)) ++k;
            act.push_back({j, k});
            j = k;
          }
          for (const LPair &p : pairs)
            for (int m1 = -p.l1; m1 <= p.l1; ++m1)
              if (abs(m3 - m1) <= p.l2)
                add_term_on(act, p.l1, m1, p.l2, out);
          conv.update(out);
        }
        const vector<complex<double>> &est = conv.estimates();
        for (const Interval &iv : ranges)
          for (size_t j = iv.jb; j < iv.je; ++j)
            out[j] = est[j];
        ConvEntry ce{modes[im], conv.shells_used(), conv.unconverged()};
#pragma omp critical(conv)
        conv_store.push_back(ce);
      } else {
        /* Shells s = max(l1, l2): sum each shell into shell_acc, then add it to the output */
        const bool diag = (l3 <= diag_l3max);
        vector<complex<double>> shell_acc(N);
        multi_array<double,3> *diag_data = nullptr;
        if (diag) diag_data = new multi_array<double,3>(boost::extents[h1lmax+1][N][2]);
        for (int sh = 0; sh <= h1lmax; ++sh) {
          vector<LPair> pairs = shell_pairs(l3, sh, dlmax, h1lmax);
          if (pairs.empty()) continue;
          fill(shell_acc.begin(), shell_acc.end(), complex<double>(0.0, 0.0));
          for (const LPair &p : pairs)
            for (int m1 = -p.l1; m1 <= p.l1; ++m1)
              if (abs(m3 - m1) <= p.l2)
                add_term(p.l1, m1, p.l2, shell_acc.data());
          for (const Interval &iv : ranges)
            for (size_t j = iv.jb; j < iv.je; ++j) {
              out[j] += shell_acc[j];
              if (diag) { (*diag_data)[sh][j][0] = real(shell_acc[j]); (*diag_data)[sh][j][1] = imag(shell_acc[j]); }
            }
        }
        if (diag) {
#pragma omp critical(diag)
          diag_store.push_back({modes[im], diag_data});
        }
      }

#pragma omp critical
      {
        if (++status % status_frequency == 0)
          cout << "Finished " << status << " of " << num_modes << " modes" << endl;
      }
    }
  }
  }
  if (num_modes % status_frequency != 0)
    cout << "Finished " << status << " of " << num_modes << " modes" << endl;

  /* Output result */
  cout << "Saving results" << endl;
  H5F src_h5("src.h5", H5F_ACC_TRUNC);
  for (const ilm_mode &mode : modes) {
    multi_array<double,2> data(boost::extents[N][2]);
    stringstream srcds;
    srcds << "src i=" << mode.i << " l=" << mode.l << " m=" << mode.m;
    for (size_t j = 0; j < N; ++j) {
      data[j][0] = real(src[mode.i][mode.l][mode.m][j]);
      data[j][1] = imag(src[mode.i][mode.l][mode.m][j]);
    }
    src_h5.write_dataset(srcds.str(), data);
  }
  multi_array<double,1> rdata(boost::extents[N]);
  for (size_t j = 0; j < N; ++j)
    rdata[j] = r[j];
  src_h5.write_dataset("r", rdata);
  if (!diag_store.empty()) {
    H5F diag_h5("shells.h5", H5F_ACC_TRUNC);
    for (auto &e : diag_store) {
      stringstream ds;
      ds << "shells i=" << e.mode.i << " l=" << e.mode.l << " m=" << e.mode.m;
      diag_h5.write_dataset(ds.str(), *e.data);
      delete e.data;
    }
    diag_h5.write_dataset("r", rdata);
    cout << "Wrote per-shell sums for " << diag_store.size() << " modes to shells.h5" << endl;
  }
  if (!conv_store.empty()) {
    H5F conv_h5("convergence.h5", H5F_ACC_TRUNC);
    size_t total_unconv = 0;
    for (auto &e : conv_store) {
      multi_array<double,1> ns(boost::extents[N]), uc(boost::extents[N]);
      for (size_t j = 0; j < N; ++j) { ns[j] = e.shells[j]; uc[j] = e.unconverged[j]; total_unconv += e.unconverged[j]; }
      stringstream a, b;
      a << "shells i=" << e.mode.i << " l=" << e.mode.l << " m=" << e.mode.m;
      b << "unconverged i=" << e.mode.i << " l=" << e.mode.l << " m=" << e.mode.m;
      conv_h5.write_dataset(a.str(), ns);
      conv_h5.write_dataset(b.str(), uc);
    }
    conv_h5.write_dataset("r", rdata);
    cout << "Convergence: " << total_unconv << " (mode, point) pairs did not reach tol with the available shells"
         << " (see convergence.h5)" << endl;
  }
  cout << "Done" << endl;
  return 0;
}
